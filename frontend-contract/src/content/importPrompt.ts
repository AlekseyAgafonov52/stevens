/** Промпт для любой нейросети: чужой календарь → JSON, который понимает «Импорт и выгрузка». */
export function importPrompt(today: string): string {
  return `Преврати мой календарь (файл или текст ниже: .ics, CSV, таблица, скриншот, список) в JSON для импорта в Стивенса.
Сегодня ${today}. Верни ТОЛЬКО JSON, без пояснений, в таком виде:

{"records": [
  {"type": "meeting", "text": "Созвон с Петей", "date": "2026-10-28", "time": "10:00", "end_time": "11:00", "remind_before": 15},
  {"type": "task", "text": "Сдать отчёт", "date": "2026-10-30", "time": null},
  {"type": "task", "text": "Прочитать книгу", "date": null},
  {"type": "reminder", "text": "Позвонить маме", "date": "2026-10-29", "time": "19:00"},
  {"type": "busy", "text": "Работа", "date": "2026-10-27", "time": "09:00", "end_time": "18:00", "repeat": {"weekdays": [0, 1, 2, 3, 4], "until": null}},
  {"type": "note", "text": "Пароль от вайфая на даче — на холодильнике"}
]}

Правила:
1. Поля только эти: type, text, date, time, end_time, remind_before, repeat. Поле id не ставь — все записи новые.
2. type: meeting — встреча в точное время; busy — занятость на интервал (работа, пары, учёба), нужны time и end_time; task — дело без точного часа или с дедлайном; reminder — напоминание в точное время; note — заметка без даты и времени.
3. date — ГГГГ-ММ-ДД, time и end_time — ЧЧ:ММ по 24 часа, в моём местном времени (не UTC). У встречи, занятости и напоминания date и time обязательны.
4. Событие на весь день — task с этой датой и "time": null. Дело без срока — task с "date": null.
5. Повтор по дням недели или каждый день — ОДНА строка: date — первый день (сегодня, если повтор начался раньше), repeat.weekdays — дни недели (0 — понедельник … 6 — воскресенье), repeat.until — последний день ГГГГ-ММ-ДД или null. Повторы раз в месяц, раз в год или через неделю распиши отдельными строками на год вперёд.
6. text — короткое название до 300 знаков; место можно дописать через « — ».
7. remind_before — только у встречи: за сколько минут напомнить (0–1440).
8. Прошедшее тоже включай — Стивенс отметит его выполненным. Отменённое не включай. Не больше 1000 строк.

Мой календарь:
`;
}
