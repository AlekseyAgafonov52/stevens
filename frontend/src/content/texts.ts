/** Подставляет значения: fill(T.show_more, { count: 10 }) → «Показать ещё (10)» */
export function fill(
  template: string,
  values: Record<string, string | number>,
): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    key in values ? String(values[key]) : `{${key}}`,
  );
}
