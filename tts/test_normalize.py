from normalize import normalize

CASES = {
    "Встреча — завтра в 15:00.": "Встреча , завтра в пятнадцать ноль-ноль.",
    "Записал, срок — до 24 октября.": "Записал, срок , до двадцать четвёртого октября.",
    "Записал на 1 января 2027 года в 9:05.": "Записал на первого января две тысячи двадцать седьмого года в девять ноль пять.",
    "На сегодня — 3 дела.": "На сегодня , три дела.",
    "Нашёл 1 запись.": "Нашёл одна запись.",
    "Нашёл 2 записи.": "Нашёл две записи.",
    "Между встречами остаётся 15 минут.": "Между встречами остаётся пятнадцать минут.",
    "Нашёл 21 запись.": "Нашёл двадцать одна запись.",
    "Обновить CRM": "Обновить си ар эм",
    "в 10:30": "в десять тридцать",
    "11 октября": "одиннадцатого октября",
    "30 декабря": "тридцатого декабря",
}
bad = 0
for src, want in CASES.items():
    got = normalize(src)
    if got != want:
        bad += 1
        print("FAIL", repr(src), "→", repr(got), "≠", repr(want))
print("ok" if not bad else f"{bad} fail")
