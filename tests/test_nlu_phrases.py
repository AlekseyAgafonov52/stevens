fails = 0
for phrase, mode in FREE:
    p = parse(phrase, NOW)
    if (p.intent, p.free_mode) != ("free", mode):
        fails += 1
        print(f"«{phrase}» → {p.intent} {p.free_mode}, ждали free {mode}")
for phrase, who in PERSON:
    p = parse(phrase, NOW)
    got = p.person if p.intent == "person" else None
    if got != who:
        fails += 1
        print(f"«{phrase}» → {p.intent} {got!r}, ждали {who!r}")
for phrase, kind, text in CASES:
    p = parse(phrase, NOW)
    if (p.type, p.text) != (kind, text):
        fails += 1
        print(f"«{phrase}» → {p.type} {p.text!r}, ждали {kind} {text!r}")
for phrase, day, time in RELATIVE:
    p = parse(phrase, NOW)
    got_day = p.date or (p.period.start if p.period else None)
    if (got_day and got_day.isoformat(), p.time) != (day, time):
        fails += 1
        print(f"«{phrase}» → {p.date} {p.time}, ждали {day} {time}")
print("fails:", fails)
sys.exit(1 if fails else 0)
